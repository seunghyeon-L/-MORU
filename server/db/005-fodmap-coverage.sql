-- ────────────────────────────────────────────
--  005 — 계산이 얼마나 추정에 기댔는지 기록한다
--
--  왜 필요한가
--    식사 1건의 6축 섭취량을 계산하려면 재료별 그램 수가 필요하다.
--    마스터에 있는 음식(김치찌개 등)은 food_ingredients 에 그램이 다 있다.
--    그런데 사용자가 직접 입력한 음식이나 직접 추가한 재료는 그램을 모른다.
--
--    모르면 카테고리 평균으로 때운다. 그건 어쩔 수 없다.
--    다만 **얼마나 때웠는지는 남겨야 한다.**
--
--    추정이 대부분인 식사를 근거로 "과당이 높았어요" 라고 말하면
--    그건 우리가 지어낸 숫자로 사용자를 판단하는 것이다. (절대 원칙 ①)
--    A-4 패턴 분석은 이 값을 보고 말할지 말지 정한다.
-- ────────────────────────────────────────────

BEGIN;

ALTER TABLE meal_fodmap
    -- 0.0 = 전부 마스터 그램 / 1.0 = 전부 카테고리 평균으로 때움
    ADD COLUMN IF NOT EXISTS estimated_ratio NUMERIC(4,3) NOT NULL DEFAULT 0;

-- 계산이 끝난 식사인지 구분한다. 재계산이 필요한 것을 찾을 수 있어야 한다.
ALTER TABLE meals
    ADD COLUMN IF NOT EXISTS fodmap_computed_at TIMESTAMPTZ;

COMMIT;
